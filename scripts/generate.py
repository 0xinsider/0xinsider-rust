RUST_KEYWORDS = {
    "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern",
    "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub",
    "ref", "return", "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe",
    "use", "where", "while", "abstract", "become", "box", "do", "final", "macro", "override", "priv",
    "typeof", "unsized", "virtual", "yield", "try", "gen",
}
NOT_RAW = {"self", "Self", "crate", "super"}


class GenerateError(Exception):
    pass


# --------------------------------------------------------------------------- names


def words(name: str) -> list[str]:
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", name)
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1 \2", name)
    return [w for w in re.split(r"[^0-9A-Za-z]+", name) if w]


def pascal(name: str) -> str:
    out = "".join(w[:1].upper() + w[1:].lower() if w.isupper() and len(w) > 1 else w[:1].upper() + w[1:] for w in words(name))
    if not out:
        raise GenerateError(f"cannot name {name!r}")
    if out[0].isdigit():
        out = "V" + out
    return out


def snake(name: str) -> str:
    out = "_".join(w.lower() for w in words(name))
    if not out:
        raise GenerateError(f"cannot name {name!r}")
    if out[0].isdigit():
        out = "n_" + out
    return out


def field_ident(name: str) -> str:
    ident = snake(name)
    if ident in NOT_RAW:
        return ident + "_"
    if ident in RUST_KEYWORDS:
        return "r#" + ident
    return ident


def bare(ident: str) -> str:
    return ident[2:] if ident.startswith("r#") else ident


def variant_ident(value: str) -> str:
    ident = pascal(value)
    return ident if ident not in RUST_KEYWORDS else ident + "_"


def rust_str(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


# --------------------------------------------------------------------------- docs


def fix_fences(text: str) -> str:
    """Rewrite code fences so each opening fence is ```text and each closing fence is ```."""
    lines = text.splitlines()
    opened = False
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith("```"):
            lines[i] = "```" if opened else "```text"
            opened = not opened
    if opened:
        lines.append("```")
    return "\n".join(lines)


def docs(text: str | None, indent: str = "") -> list[str]:
    if not text:
        return []
    text = fix_fences(text.strip())
    return [f"{indent}/// {line.strip()}".rstrip() for line in text.splitlines()]


# --------------------------------------------------------------------------- schema helpers


def ref_name(ref: str) -> str:
    prefix = "#/components/schemas/"
    if not ref.startswith(prefix):
        raise GenerateError(f"unsupported $ref outside components.schemas: {ref}")
    return ref[len(prefix):]


def is_null_schema(schema: dict) -> bool:
    return schema.get("type") == "null" or schema.get("enum") == [None]


def split_nullable(schema: dict) -> tuple[dict, bool]:
    """Return (the schema without its null arm, whether null is allowed)."""
    nullable = bool(schema.get("nullable"))
    schema = dict(schema)
    schema.pop("nullable", None)
    types = schema.get("type")
    if isinstance(types, list):
        if "null" in types:
            nullable = True
        rest = [t for t in types if t != "null"]
        if len(rest) != 1:
            raise GenerateError(f"unsupported multi-type schema {types}")
        schema["type"] = rest[0]
    if isinstance(schema.get("enum"), list) and None in schema["enum"]:
        nullable = True
        schema["enum"] = [v for v in schema["enum"] if v is not None]
    for key in ("oneOf", "anyOf"):
        arms = schema.get(key)
        if isinstance(arms, list) and any(is_null_schema(a) for a in arms):
            nullable = True
            rest = [a for a in arms if not is_null_schema(a)]
            if len(rest) == 1:
                merged = {k: v for k, v in schema.items() if k != key}
                merged.update(rest[0])
                schema = merged
            else:
                schema[key] = rest
    return schema, nullable


def string_enum(schema: dict) -> list[str] | None:
    values = schema.get("enum")
    if not isinstance(values, list):
        return None
    values = [v for v in values if v is not None]
    if not values or not all(isinstance(v, str) for v in values):
        return None
    if len(values) < 2:
        return None  # a single-value enum is a constant; it stays a String
    return values


# --------------------------------------------------------------------------- enum naming


class EnumNames:
    """Names every string enum by its value set, so one set is one Rust type.

    A set a component schema names keeps that name. Otherwise the set is named
    after the property that most often carries it (`grade`, `side`); when two
    sets want one name, the set used more often keeps it and the other is named
    after its first owner plus the property.
    """

    def __init__(self, components: dict):
        self.by_values: dict[tuple, str] = {}
        self.occurrences: OrderedDict[tuple, list[tuple[str, str]]] = OrderedDict()
        for name, schema in components.items():
            values = string_enum(split_nullable(schema)[0])
            if values:
                self.by_values[tuple(values)] = name

    def record(self, values: list[str], owner: str, prop: str) -> None:
        key = tuple(values)
        if key not in self.by_values:
            self.occurrences.setdefault(key, []).append((owner, prop or owner))

    def assign(self, taken: set[str]) -> None:
        wanted: OrderedDict[str, list[tuple[int, tuple]]] = OrderedDict()
        for key, occurrences in self.occurrences.items():
            # `min_grade` and `grade` carry one set; name it after the value, not the filter.
            counts = Counter(re.sub(r"^min_", "", prop) for _, prop in occurrences)
            best = sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[0][0]
            wanted.setdefault(pascal(best), []).append((len(occurrences), key))
        for key in self.occurrences:
            override = ENUM_NAME_OVERRIDES.get(key[0])
            if override:
                taken.add(override)
                self.by_values[key] = override
        unused = set(ENUM_NAME_OVERRIDES) - {key[0] for key in self.occurrences}
        for first in sorted(unused):
            print(f"warning: ENUM_NAME_OVERRIDES[{first!r}] matches no enum; remove it", file=sys.stderr)
        for name, claims in wanted.items():
            claims = [claim for claim in claims if claim[1] not in self.by_values]
            claims.sort(key=lambda claim: -claim[0])
            for index, (_, key) in enumerate(claims):
                candidate = name
                if index > 0 or candidate in taken:
                    owner, prop = self.occurrences[key][0]
                    candidate = pascal(owner) + pascal(prop)
                base, n = candidate, 2
                while candidate in taken:
                    candidate, n = f"{base}{n}", n + 1
                taken.add(candidate)
                self.by_values[key] = candidate

    def name(self, values: list[str]) -> str:
        return self.by_values[tuple(values)]

    def names(self) -> set[str]:
        return set(self.by_values.values())


def collect_enums(node, enums: EnumNames, owner: str, prop: str) -> None:
    """Record each inline string enum under a schema with the property that carries it."""
    if isinstance(node, list):
        for item in node:
            collect_enums(item, enums, owner, prop)
        return
    if not isinstance(node, dict) or "$ref" in node:
        return
    values = string_enum(split_nullable(node)[0])
    if values:
        enums.record(values, owner, prop)
    for key, value in node.items():
        if key == "properties" and isinstance(value, dict):
            for name, child in value.items():
                collect_enums(child, enums, owner + pascal(prop) if prop else owner, name)
        elif key in ("items", "additionalProperties", "oneOf", "anyOf", "allOf"):
            collect_enums(value, enums, owner, prop)


# --------------------------------------------------------------------------- type model


class Field:
    def __init__(self, json_name: str, ident: str, rust_type: str, doc: str | None,
                 required: bool, nullable: bool, flatten: bool = False):
        self.json_name = json_name
        self.ident = ident
        self.rust_type = rust_type
        self.doc = doc
        self.required = required
        self.nullable = nullable
        self.flatten = flatten

    @property
    def optional(self) -> bool:
        return not self.flatten and (not self.required or self.nullable)


class Param:
    """One operation parameter as the generated method sees it."""

    def __init__(self, spec: dict, ident: str, rust_type: str):
        self.spec = spec
        self.name = spec["name"]
        self.location = spec["in"]
        self.ident = ident
        self.rust_type = rust_type


class Generator:
    def __init__(self, doc: dict):
        self.doc = doc
        self.components: dict = doc.get("components", {}).get("schemas", {})
        self.enums = EnumNames(self.components)
        self.enum_defs: OrderedDict[str, tuple[list[str], str | None]] = OrderedDict()
        self.structs: OrderedDict[str, tuple[list[Field], str | None]] = OrderedDict()
        self.unions: OrderedDict[str, tuple[str, list[tuple[str, str, str]], str | None]] = OrderedDict()
        self.aliases: OrderedDict[str, tuple[str, str | None]] = OrderedDict()
        self.params: OrderedDict[str, list[str]] = OrderedDict()
        self.request_roots: set[str] = set()
        self.boxed_edges: set[tuple[str, str]] = set()
        self.list_pages: dict[str, tuple[str, bool, bool, bool]] = {}
        self.cursor_params: set[str] = set()
        self.response_types: OrderedDict[str, str] = OrderedDict()
        self.name_owner: dict[str, str] = {}
        self.body_types: OrderedDict[str, str] = OrderedDict()

    # ---------------------------------------------------------------- walk

    def operations(self):
        for path, item in self.doc.get("paths", {}).items():
            for method in METHODS:
                operation = item.get(method)
                if isinstance(operation, dict):
                    yield operation["operationId"], method, path, operation

    def resolve_param(self, param: dict) -> dict:
        if "$ref" not in param:
            return param
        prefix = "#/components/parameters/"
        ref = param["$ref"]
        if not ref.startswith(prefix):
            raise GenerateError(f"unsupported parameter $ref {ref}")
        return self.doc["components"]["parameters"][ref[len(prefix):]]

    def json_body_schema(self, operation: dict):
        body = operation.get("requestBody")
        if not body:
            return None
        content = body.get("content") or {}
        if "application/json" not in content:
            raise GenerateError(f"{operation['operationId']}: unsupported request body {list(content)}")
        return content["application/json"].get("schema")

    def success(self, operation: dict) -> tuple[str, str, dict | None, bool]:
        """(kind, accept, schema, may_be_empty); kind is json, text or download."""
        responses = operation.get("responses", {})
        codes = sorted(c for c in responses if c.startswith("2"))
        if not codes:
            if any(c in responses for c in REDIRECT_CODES):
                return "download", "*/*", None, False
            raise GenerateError(f"{operation['operationId']} documents no 2xx and no redirect")
        schemas, empty = [], False
        for code in codes:
            content = responses[code].get("content") or {}
            if not content:
                empty = True
            elif "application/json" in content:
                schemas.append(content["application/json"].get("schema"))
            elif all(media.startswith("text/") and media != "text/event-stream" for media in content):
                return "text", next(iter(content)), None, False
            else:
                raise GenerateError(f"{operation['operationId']}: unsupported success media {list(content)}")
        if not schemas:
            raise GenerateError(f"{operation['operationId']}: no success body")
        first = json.dumps(schemas[0], sort_keys=True)
        if any(json.dumps(s, sort_keys=True) != first for s in schemas[1:]):
            raise GenerateError(f"{operation['operationId']}: 2xx responses carry different schemas")
        return "json", "application/json", schemas[0], empty

    # ---------------------------------------------------------------- preparation

    def prepare_enums(self) -> None:
        for name, schema in self.components.items():
            collect_enums(schema, self.enums, name, "")
        for op_id, _, _, operation in self.operations():
            owner = pascal(op_id)
            for param in operation.get("parameters", []):
                param = self.resolve_param(param)
                collect_enums(param.get("schema", {}), self.enums, owner, param["name"])
            body = self.json_body_schema(operation)
            if body is not None:
                collect_enums(body, self.enums, owner + "Body", "")
            for code, response in operation.get("responses", {}).items():
                schema = (response.get("content") or {}).get("application/json", {}).get("schema")
                if schema is not None and code.startswith("2"):
                    collect_enums(schema, self.enums, owner + "Response", "")
        self.enums.assign(set(self.components) | {"Client", "Error", "Result", "Operation", "Download"})

    def find_boxed_edges(self) -> None:
        """Box a direct (non-collection) reference that closes a cycle."""
        graph = {name: set(self.direct_refs(schema)) for name, schema in self.components.items()}

        def reaches(start: str, goal: str) -> bool:
            seen, stack = set(), [start]
            while stack:
                node = stack.pop()
                if node == goal:
                    return True
                if node not in seen:
                    seen.add(node)
                    stack.extend(graph.get(node, ()))
            return False

        for name, targets in graph.items():
            for target in targets:
                if reaches(target, name):
                    self.boxed_edges.add((name, target))

    def direct_refs(self, schema) -> list[str]:
        if not isinstance(schema, dict):
            return []
        if "$ref" in schema:
            return [ref_name(schema["$ref"])]
        out: list[str] = []
        for child in (schema.get("properties") or {}).values():
            out.extend(self.direct_refs(child))
        for key in ("allOf", "oneOf", "anyOf"):
            for child in schema.get(key) or []:
                out.extend(self.direct_refs(child))
        return out

    def component_nullable(self, name: str) -> bool:
        return split_nullable(self.components[name])[1]

    # ---------------------------------------------------------------- types

    def type_name(self, hint: str, schema: dict, exact: bool) -> str:
        """The Rust name for a nested object or union. A component keeps its own
        name (`exact`); an inline schema takes `hint` unless a component, an enum
        or a different inline schema already has it, and then `hint2`, `hint3`, ..."""
        key = json.dumps(schema, sort_keys=True)
        if exact:
            self.name_owner[hint] = key
            return hint
        candidate, n = hint, 2
        if hint in INLINE_NAME_OVERRIDES and (hint in self.components or self.name_owner.get(hint, key) != key):
            hint = candidate = INLINE_NAME_OVERRIDES[hint]
        while True:
            owner = self.name_owner.get(candidate)
            if owner == key:
                return candidate
            if owner is None and candidate not in self.components and candidate not in self.enums.names():
                self.name_owner[candidate] = key
                return candidate
            candidate, n = f"{hint}{n}", n + 1

    def rust_type(self, schema: dict, hint: str, owner: str, exact: bool = False) -> tuple[str, bool]:
        """Return (rust type, nullable) for a schema, defining any type it nests."""
        if not isinstance(schema, dict):
            raise GenerateError(f"schema for {hint} is not an object")
        schema, nullable = split_nullable(schema)
        if "$ref" in schema:
            target = ref_name(schema["$ref"])
            if target not in self.components:
                raise GenerateError(f"$ref names a schema the document does not define: {target}")
            rust = f"Box<{target}>" if (owner, target) in self.boxed_edges else target
            return rust, nullable or self.component_nullable(target)
        if "allOf" in schema:
            arms = schema["allOf"]
            if len(arms) == 1 and not schema.get("properties"):
                inner, inner_nullable = self.rust_type(arms[0], hint, owner)
                return inner, nullable or inner_nullable
            name = self.type_name(hint, schema, exact)
            self.define_struct(name, schema)
            return name, nullable
        if "oneOf" in schema or "anyOf" in schema:
            arms = schema.get("oneOf") or schema.get("anyOf")
            if schema.get("discriminator") and all("$ref" in arm for arm in arms):
                name = self.type_name(hint, schema, exact)
                self.define_union(name, schema)
                return name, nullable
            # Deliberately untyped: an untagged union of scalars (a JSON-RPC id).
            return "serde_json::Value", nullable
        kind = schema.get("type")
        if kind is None:
            if "properties" in schema:
                kind = "object"
            elif isinstance(schema.get("const"), str) or string_enum(schema):
                kind = "string"
            else:
                return "serde_json::Value", nullable
        if kind == "string":
            values = string_enum(schema)
            if values:
                name = self.enums.name(values)
                if name not in self.enum_defs:
                    self.enum_defs[name] = (values, None)
                return name, nullable
            return "String", nullable
        if kind == "integer":
            return "i64", nullable
        if kind == "number":
            return "f64", nullable
        if kind == "boolean":
            return "bool", nullable
        if kind == "array":
            items = schema.get("items")
            if items is None:
                return "Vec<serde_json::Value>", nullable
            inner, inner_nullable = self.rust_type(items, hint + "Item", owner)
            if inner.startswith("Box<"):
                inner = inner[4:-1]  # a Vec already puts its elements on the heap
            return (f"Vec<Option<{inner}>>" if inner_nullable else f"Vec<{inner}>"), nullable
        if kind == "object":
            if schema.get("properties"):
                name = self.type_name(hint, schema, exact)
                self.define_struct(name, schema)
                return name, nullable
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                inner, inner_nullable = self.rust_type(extra, hint + "Value", owner)
                inner = f"Option<{inner}>" if inner_nullable else inner
                return f"std::collections::BTreeMap<String, {inner}>", nullable
            return "serde_json::Map<String, serde_json::Value>", nullable
        raise GenerateError(f"unsupported schema type {kind!r} at {hint}")

    def define_struct(self, name: str, schema: dict) -> None:
        if name in self.structs:
            return
        self.structs[name] = ([], None)  # reserve the name before recursing
        fields: list[Field] = []
        for arm in schema.get("allOf") or []:
            if "$ref" in arm:
                target = ref_name(arm["$ref"])
                fields.append(Field(target, field_ident(target), target, None, True, False, flatten=True))
            else:
                fields.extend(self.object_fields(name, split_nullable(arm)[0]))
        fields.extend(self.object_fields(name, schema))
        if schema.get("additionalProperties") is True:
            fields.append(Field("", "extra", "serde_json::Map<String, serde_json::Value>",
                                "Keys this release does not name. The API adds fields additively; they are kept here.",
                                True, False, flatten=True))
        idents = [f.ident for f in fields]
        if len(set(idents)) != len(idents):
            raise GenerateError(f"{name} has two fields with one Rust name: {idents}")
        self.structs[name] = (fields, schema.get("description"))

    def object_fields(self, owner: str, schema: dict) -> list[Field]:
        required = set(schema.get("required") or [])
        fields = []
        for json_name, prop in (schema.get("properties") or {}).items():
            rust, nullable = self.rust_type(prop, owner + pascal(json_name), owner)
            description = prop.get("description") if isinstance(prop, dict) else None
            fields.append(Field(json_name, field_ident(json_name), rust, description, json_name in required, nullable))
        return fields

    def define_union(self, name: str, schema: dict) -> None:
        if name in self.unions:
            return
        discriminator = schema["discriminator"]
        tag = discriminator["propertyName"]
        by_target = {ref_name(v): k for k, v in (discriminator.get("mapping") or {}).items()}
        variants = []
        for arm in schema.get("oneOf") or schema.get("anyOf"):
            target = ref_name(arm["$ref"])
            if target not in by_target:
                raise GenerateError(f"{name}: {target} has no discriminator mapping value")
            variants.append((variant_ident(by_target[target]), by_target[target], target))
        self.unions[name] = (tag, variants, schema.get("description"))

    # ---------------------------------------------------------------- request-ness

    def request_types(self) -> set[str]:
        """Every struct or union a caller builds: request bodies and what they nest."""
        known = set(self.structs) | set(self.unions) | set(self.aliases)
        out, stack = set(), list(self.request_roots)
        while stack:
            name = stack.pop()
            if name in out or name not in known:
                continue
            out.add(name)
            referenced: list[str] = []
            if name in self.structs:
                referenced = [f.rust_type for f in self.structs[name][0]]
            elif name in self.unions:
                referenced = [target for _, _, target in self.unions[name][1]]
            elif name in self.aliases:
                referenced = [self.aliases[name][0]]
            for rust in referenced:
                stack.extend(re.findall(r"[A-Z][A-Za-z0-9]*", rust))
        return out

    # ---------------------------------------------------------------- generate

    def generate(self) -> tuple[str, str, int]:
        self.prepare_enums()
        self.find_boxed_edges()
        for name, schema in self.components.items():
            stripped, _ = split_nullable(schema)
            values = string_enum(stripped)
            if values:
                self.enum_defs[name] = (values, schema.get("description"))
                continue
            rust, _ = self.rust_type(schema, name, name, exact=True)
            if rust != name:
                self.aliases[name] = (rust, schema.get("description"))

        table: list[str] = []
        methods: list[str] = []
        count = 0
        for op_id, method, path, operation in self.operations():
            count += 1
            if op_id in SKIPPED_OPERATIONS:
                table.append(self.operation_const(op_id, method, path, operation, "text/event-stream" if SKIPPED_OPERATIONS[op_id] == "stream" else "application/json"))
                continue
            kind, accept, schema, may_be_empty = self.success(operation)
            table.append(self.operation_const(op_id, method, path, operation, accept))
            methods.extend(self.operation_method(op_id, method, path, operation, kind, schema, may_be_empty))
            methods.append("")
        return self.render_models(), self.render_operations(table, methods), count

    def operation_const(self, op_id: str, method: str, path: str, operation: dict, accept: str) -> str:
        params = [self.resolve_param(p) for p in operation.get("parameters", [])]
        keyed = any(p["in"] == "header" and p["name"].lower() == "idempotency-key" for p in params)
        if method == "get" or op_id in READ_ONLY_POSTS:
            retry = "RetryClass::Read"
        elif keyed:
            retry = "RetryClass::Keyed"
        else:
            retry = "RetryClass::Never"
        security = operation.get("security", self.doc.get("security", []))
        return (
            f"    /// `{method.upper()} {path}`\n"
            f"    pub const {snake(op_id).upper()}: Operation = Operation {{\n"
            f"        id: {rust_str(op_id)},\n"
            f"        method: {rust_str(method.upper())},\n"
            f"        path: {rust_str(path)},\n"
            f"        accept: {rust_str(accept)},\n"
            f"        retry: {retry},\n"
            f"        requires_credential: {'true' if security else 'false'},\n"
            f"    }};"
        )

    def param_type(self, param: dict, owner: str) -> str:
        rust, _ = self.rust_type(param.get("schema", {}), owner + pascal(param["name"]), owner)
        return rust

    def operation_method(self, op_id, method, path, operation, kind, schema, may_be_empty) -> list[str]:
        name = snake(op_id)
        prefix = pascal(op_id)
        specs = [self.resolve_param(p) for p in operation.get("parameters", [])]
        if any(p["in"] == "cookie" for p in specs):
            raise GenerateError(f"{op_id}: cookie parameters are not supported")
        path_params = [p for p in specs if p["in"] == "path"]
        # `expand[]` and `wallet[]` are backward-compatible spellings of `expand`
        # and `wallet`; this client always sends the canonical name.
        query = [p for p in specs if p["in"] == "query" and not p["name"].endswith("[]")]
        headers = [p for p in specs if p["in"] == "header" and p["name"] not in CLIENT_OWNED_HEADERS]
        required = [Param(p, field_ident(p["name"]), self.param_type(p, prefix)) for p in query if p.get("required")]
        optional = [Param(p, field_ident(p["name"]), self.param_type(p, prefix)) for p in query if not p.get("required")]
        optional += [Param(p, field_ident(p["name"]), "String") for p in headers]

        if kind == "json":
            response_type, _ = self.rust_type(schema, prefix + "Response", prefix + "Response")
            returns = f"Option<{response_type}>" if may_be_empty else response_type
            self.response_types[op_id] = response_type
        elif kind == "text":
            response_type = returns = "String"
        else:
            response_type = returns = "Download"

        body_type = None
        body_schema = self.json_body_schema(operation)
        if body_schema is not None:
            body_type, _ = self.rust_type(body_schema, prefix + "Body", prefix + "Body")
            self.body_types[op_id] = body_type
            self.request_roots.update(re.findall(r"[A-Z][A-Za-z0-9]*", body_type))

        args: list[str] = []
        path_expr, fmt_args = path, []
        for p in path_params:
            ident = field_ident(p["name"])
            kind_ = (p.get("schema") or {}).get("type")
            if kind_ == "integer":
                args.append(f"{ident}: i64")
                fmt_args.append(f"{bare(ident)} = {ident}")
            elif kind_ == "string":
                args.append(f"{ident}: &str")
                fmt_args.append(f"{bare(ident)} = encode_path_segment({ident})")
            else:
                raise GenerateError(f"{op_id}: unsupported path parameter type {kind_}")
            path_expr = path_expr.replace("{" + p["name"] + "}", "{" + bare(ident) + "}")
        for param in required:
            if param.rust_type.startswith("Vec<"):
                raise GenerateError(f"{op_id}: a required array query parameter is not supported")
            args.append(f"{param.ident}: {'&str' if param.rust_type == 'String' else param.rust_type}")
        if body_type is not None:
            args.append(f"body: &{body_type}")
        params_type = None
        if optional:
            params_type = prefix + "Params"
            args.append(f"params: &{params_type}")
            self.params[params_type] = self.render_params(params_type, op_id, method, path, optional)
            if any(p.ident == "cursor" for p in optional):
                self.cursor_params.add(params_type)

        lines = [f"    /// {(operation.get('summary') or op_id).strip()}", "    ///", f"    /// `{method.upper()} {path}`"]
        if operation.get("description"):
            lines.append("    ///")
            lines.extend(docs(operation["description"], "    "))
        if kind == "download":
            lines += [
                "    ///",
                "    /// The API answers with a redirect to the file. It is followed once, by a fresh",
                "    /// request that carries no credential, and the file comes back as a streaming",
                "    /// [`Download`].",
            ]
        if may_be_empty:
            lines += ["    ///", "    /// Returns `None` when the API answers with an empty success body."]
        lines.append(f"    pub async fn {name}({', '.join(['&self'] + args)}) -> Result<{returns}> {{")
        if fmt_args:
            lines.append(f"        let path = format!({rust_str(path_expr)}, {', '.join(fmt_args)});")
        else:
            lines.append(f"        let path = String::from({rust_str(path)});")
        mutable = bool(required or optional or body_type)
        lines.append(f"        let {'mut ' if mutable else ''}call = Call::new(&Operation::{snake(op_id).upper()}, path);")
        for param in required:
            lines.append(f"        call.query({rust_str(param.name)}, {self.query_value(param.ident, param.rust_type)});")
        for param in optional:
            if param.location == "header":
                lines.append(f"        call.header({rust_str(param.name)}, params.{param.ident}.as_deref());")
            elif param.rust_type.startswith("Vec<"):
                lines.append(f"        for value in &params.{param.ident} {{")
                lines.append(f"            call.query({rust_str(param.name)}, {self.query_value('value', param.rust_type[4:-1])});")
                lines.append("        }")
            else:
                lines.append(f"        if let Some(value) = &params.{param.ident} {{")
                lines.append(f"            call.query({rust_str(param.name)}, {self.query_value('value', param.rust_type)});")
                lines.append("        }")
        if body_type is not None:
            lines.append("        call.json(body)?;")
        send = {"json": "send_json_optional" if may_be_empty else "send_json", "text": "send_text", "download": "send_download"}[kind]
        lines.append(f"        self.{send}(call).await")
        lines.append("    }")

        if kind == "json" and not may_be_empty and response_type in self.structs:
            fields = {f.json_name: f for f in self.structs[response_type][0]}
            data, has_more, cursor = fields.get("data"), fields.get("has_more"), fields.get("next_cursor")
            if data and has_more and cursor and data.rust_type.startswith("Vec<") and cursor.rust_type == "String":
                self.list_pages[response_type] = (data.rust_type[4:-1], data.optional, has_more.optional, cursor.optional)
        return lines

    def query_value(self, ident: str, rust: str) -> str:
        if rust == "String":
            return f"{ident}.to_string()"
        if rust in ("i64", "f64", "bool"):
            return f"{ident}.to_string()"
        if rust in self.enum_defs:
            return f"{ident}.as_str().to_owned()"
        raise GenerateError(f"unsupported query parameter type {rust}")

    def render_params(self, name: str, op_id: str, method: str, path: str, fields: list[Param]) -> list[str]:
        lines = [
            f"/// Optional parameters for [`Client::{snake(op_id)}`] (`{method.upper()} {path}`).",
            "///",
            "/// Start from `Default::default()` and set what you need, through the field or the",
            "/// chainable setter of the same name.",
            "#[derive(Debug, Clone, Default, PartialEq)]",
            "#[non_exhaustive]",
            f"pub struct {name} {{",
        ]
        for param in fields:
            lines.extend(docs(param.spec.get("description"), "    "))
            if param.location == "header":
                lines.append("    ///")
                lines.append(f"    /// Sent as the `{param.name}` header.")
            ty = param.rust_type if param.rust_type.startswith("Vec<") else f"Option<{param.rust_type}>"
            lines.append(f"    pub {param.ident}: {ty},")
        lines.append("}")
        lines.append("")
        lines.append(f"impl {name} {{")
        for param in fields:
            lines.append(f"    /// Sets `{param.name}`.")
            lines.append("    #[must_use]")
            if param.rust_type.startswith("Vec<"):
                inner = param.rust_type[4:-1]
                if inner == "String":
                    lines.append(f"    pub fn {param.ident}<I, S>(mut self, values: I) -> Self")
                    lines.append("    where")
                    lines.append("        I: IntoIterator<Item = S>,")
                    lines.append("        S: Into<String>,")
                    lines.append("    {")
                    lines.append(f"        self.{param.ident} = values.into_iter().map(Into::into).collect();")
                else:
                    lines.append(f"    pub fn {param.ident}<I: IntoIterator<Item = {inner}>>(mut self, values: I) -> Self {{")
                    lines.append(f"        self.{param.ident} = values.into_iter().collect();")
            elif param.rust_type == "String":
                lines.append(f"    pub fn {param.ident}(mut self, value: impl Into<String>) -> Self {{")
                lines.append(f"        self.{param.ident} = Some(value.into());")
            else:
                lines.append(f"    pub fn {param.ident}(mut self, value: {param.rust_type}) -> Self {{")
                lines.append(f"        self.{param.ident} = Some(value);")
            lines.append("        self")
            lines.append("    }")
        lines.append("}")
        return lines

