def load(source: str) -> bytes:
    if source.startswith(("http://", "https://")):
        request = urllib.request.Request(source, headers={"User-Agent": USER_AGENT})
        with urllib.request.urlopen(request, timeout=60) as response:  # noqa: S310 - fixed https source
            return response.read()
    return Path(source).read_bytes()


def resolve_app_commit(explicit: str | None) -> str | None:
    candidate = explicit or os.environ.get("OXINSIDER_APP_COMMIT")
    if candidate:
        return candidate
    url = f"https://api.github.com/repos/{APP_REPOSITORY}/commits?path={APP_SPEC_PATH}&per_page=1"
    headers = {"User-Agent": USER_AGENT, "Accept": "application/vnd.github+json"}
    token = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
    if token:
        headers["Authorization"] = f"Bearer {token}"
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=30) as response:  # noqa: S310
            commits = json.load(response)
    except (OSError, ValueError) as error:
        print(f"warning: app commit not resolved from the GitHub API ({error}); recording None", file=sys.stderr)
        return None
    if not isinstance(commits, list) or not commits:
        print("warning: the GitHub API listed no commit for the document; recording None", file=sys.stderr)
        return None
    return str(commits[0]["sha"])


def render_provenance(raw: bytes, doc: dict, source: str, app_commit: str | None, count: int) -> str:
    version = doc.get("info", {}).get("version", "unknown")
    commit = "None" if app_commit is None else f"Some({rust_str(app_commit)})"
    return (
        HEADER
        + "//! Which OpenAPI document this release was generated from.\n"
        "//!\n"
        "//! Compare [`OPENAPI_SHA256`] with `shasum -a 256` of\n"
        "//! <https://0xinsider.com/api/v1/openapi.json> to see whether a release is behind the API.\n"
        "\n"
        "/// Where the document came from: the published URL, or the app repository path when generated from a file.\n"
        f"pub const OPENAPI_SOURCE: &str = {rust_str(source)};\n"
        "/// SHA-256 of the document bytes as fetched.\n"
        f"pub const OPENAPI_SHA256: &str = {rust_str(hashlib.sha256(raw).hexdigest())};\n"
        "/// The document's `info.version`.\n"
        f"pub const OPENAPI_VERSION: &str = {rust_str(version)};\n"
        "/// Operations in the document, including the two read by hand (the stream) or refused (`GET /api/v1/mcp`).\n"
        f"pub const OPERATION_COUNT: usize = {count};\n"
        "/// The repository that owns the document.\n"
        f"pub const APP_REPOSITORY: &str = {rust_str(APP_REPOSITORY)};\n"
        "/// The document's path in that repository.\n"
        f"pub const APP_SPEC_PATH: &str = {rust_str(APP_SPEC_PATH)};\n"
        "/// The app repository commit that last changed the document, or `None` when it could not be resolved.\n"
        f"pub const APP_COMMIT: Option<&str> = {commit};\n"
    )


def rustfmt(text: str) -> str:
    """Format generated Rust the way `cargo fmt` would, so the files never drift from it."""
    result = subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout"],
        input=text, capture_output=True, text=True, cwd=ROOT, check=False,
    )
    if result.returncode != 0:
        raise GenerateError(f"rustfmt failed:\n{result.stderr}")
    return result.stdout


def main(argv: list[str]) -> int:
    check = "--check" in argv
    argv = [a for a in argv if a != "--check"]
    app_commit = None
    if "--app-commit" in argv:
        index = argv.index("--app-commit")
        app_commit = argv[index + 1]
        del argv[index : index + 2]
    source = argv[0] if argv else (str(ROOT / "openapi.json") if check else DEFAULT_SOURCE)
    raw = load(source)
    doc = json.loads(raw)
    generator = Generator(doc)
    try:
        models, operations, count = generator.generate()
    except GenerateError as error:
        print(f"generate: {error}", file=sys.stderr)
        return 1
    source_label = DEFAULT_SOURCE if source.startswith(("http://", "https://")) or check else f"{APP_REPOSITORY}:{APP_SPEC_PATH}"
    try:
        outputs = {
            ROOT / "src" / "models.rs": rustfmt(models),
            ROOT / "src" / "operations.rs": rustfmt(operations),
            ROOT / "tests" / "support" / "generated.rs": rustfmt(generator.render_test_support()),
        }
    except GenerateError as error:
        print(f"generate: {error}", file=sys.stderr)
        return 1
    if check:
        stale = [str(p.relative_to(ROOT)) for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        if stale:
            print(f"generate --check: stale {', '.join(stale)}; run python3 scripts/generate.py", file=sys.stderr)
            return 1
        print(f"generate --check: OK ({len(generator.components)} schemas, {count} operations)")
        return 0
    commit = resolve_app_commit(app_commit)
    outputs[ROOT / "src" / "provenance.rs"] = rustfmt(render_provenance(raw, doc, source_label, commit, count))
    (ROOT / "openapi.json").write_bytes(raw)
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(
        f"generated {count} operations and {len(generator.components)} schemas from {source_label} "
        f"(sha256 {hashlib.sha256(raw).hexdigest()}, app commit {commit or 'unknown'})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
