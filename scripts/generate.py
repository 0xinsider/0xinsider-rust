#!/usr/bin/env python3
"""Generate the typed Rust client from the 0xinsider OpenAPI document.

Usage:
    python3 scripts/generate.py                 # fetch https://0xinsider.com/api/v1/openapi.json
    python3 scripts/generate.py path/to/openapi.json
    python3 scripts/generate.py --check         # exit 1 when the generated files are stale
    python3 scripts/generate.py --app-commit SHA

Writes, and never hand-edit any of them:
    openapi.json          the document exactly as fetched (the tests read its examples)
    src/models.rs         one Rust type per schema the document names or nests
    src/operations.rs     the operation table, a params struct and a Client method per operation
    src/provenance.rs     which document this release was generated from
    tests/support/generated.rs  operation ids and schema names mapped to Rust types, for the tests

The generator understands every construct the document uses today and raises on
one it does not, rather than emitting an untyped value that hides the gap. The
exceptions are deliberate and listed where they are handled: an untagged
`oneOf`/`anyOf` (a JSON-RPC id that is a string or a number) becomes
`serde_json::Value`, and an integer enum stays `i64`.

The app commit is `--app-commit`, the OXINSIDER_APP_COMMIT environment variable,
or a lookup of the GitHub commits API (GH_TOKEN is used when set). One that cannot
be resolved is recorded as `None` and reported on stderr, never guessed.
"""

