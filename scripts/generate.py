    def render_test_support(self) -> str:
        """Maps operation ids and schema names to their Rust types, for the
        tests that decode every documented example (and live sandbox answers)."""

        def arms(mapping) -> list[str]:
            return [f"        {rust_str(key)} => Some(check::<{rust}>(value))," for key, rust in mapping]

        components = [(name, name) for name in self.components if name in self.structs or name in self.unions
                      or name in self.enum_defs or name in self.aliases]
        out = [
            HEADER,
            "//! Operation ids and schema names mapped to their Rust types, for the example tests.",
            "",
            "#![allow(dead_code)]",
            "",
            "use oxinsider::models::*;",
            "",
            "fn check<T: serde::de::DeserializeOwned>(value: serde_json::Value) -> Result<(), String> {",
            "    serde_path_to_error::deserialize::<_, T>(value).map(drop).map_err(|error| format!(\"at `{}`: {}\", error.path(), error.inner()))",
            "}",
            "",
            "/// Decode a 2xx body of `operation` into its response type.",
            "pub fn decode_response(operation: &str, value: serde_json::Value) -> Option<Result<(), String>> {",
            "    match operation {",
            *arms(self.response_types.items()),
            "        _ => None,",
            "    }",
            "}",
            "",
            "/// Decode a request body of `operation` into its body type.",
            "pub fn decode_body(operation: &str, value: serde_json::Value) -> Option<Result<(), String>> {",
            "    match operation {",
            *arms(self.body_types.items()),
            "        _ => None,",
            "    }",
            "}",
            "",
            "/// Decode a value into the type for a component schema.",
            "pub fn decode_component(name: &str, value: serde_json::Value) -> Option<Result<(), String>> {",
            "    match name {",
            *arms(components),
            "        _ => None,",
            "    }",
            "}",
        ]
        return "\n".join(out).rstrip() + "\n"

    def render_struct(self, name: str, request: bool) -> list[str]:
        fields, description = self.structs[name]
        derives = ["Debug", "Clone", "PartialEq", "Serialize", "Deserialize"]
        if request and all(f.optional for f in fields):
            derives.append("Default")
        lines = docs(description)
        lines.append(f"#[derive({', '.join(derives)})]")
        if not request:
            lines.append("#[non_exhaustive]")
        lines.append(f"pub struct {name} {{")
        for field in fields:
            lines.extend(docs(field.doc, "    "))
            attrs = []
            if field.flatten:
                attrs.append("flatten")
            else:
                if bare(field.ident) != field.json_name:
                    attrs.append(f"rename = {rust_str(field.json_name)}")
                if field.optional:
                    attrs.append("default")
                if not field.required:
                    attrs.append('skip_serializing_if = "Option::is_none"')
            if attrs:
                lines.append(f"    #[serde({', '.join(attrs)})]")
            rust = f"Option<{field.rust_type}>" if field.optional else field.rust_type
            lines.append(f"    pub {field.ident}: {rust},")
        lines.append("}")
        return lines

    def render_union(self, name: str) -> list[str]:
        tag, variants, description = self.unions[name]
        lines = docs(description)
        if lines:
            lines.append("///")
        lines += [
            f"/// Discriminated by `{tag}`. A `{tag}` this release does not know is kept whole in",
            "/// `Unknown`, so a new kind never fails a response.",
            "#[derive(Debug, Clone, PartialEq)]",
            "#[non_exhaustive]",
            f"pub enum {name} {{",
        ]
        for ident, value, target in variants:
            lines.append(f"    /// `{tag}` is `{value}`.")
            lines.append(f"    {ident}({target}),")
        lines.append(f"    /// A `{tag}` this release does not know, kept as sent.")
        lines.append("    Unknown(serde_json::Value),")
        lines.append("}")
        lines.append("")
        lines.append(f"impl<'de> Deserialize<'de> for {name} {{")
        lines.append("    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {")
        lines.append("        let value = serde_json::Value::deserialize(deserializer)?;")
        lines.append(f"        match value.get({rust_str(tag)}).and_then(serde_json::Value::as_str) {{")
        for ident, value, _ in variants:
            lines.append(f"            Some({rust_str(value)}) => serde_json::from_value(value).map(Self::{ident}).map_err(de::Error::custom),")
        lines.append("            _ => Ok(Self::Unknown(value)),")
        lines.append("        }")
        lines.append("    }")
        lines.append("}")
        lines.append("")
        lines.append(f"impl Serialize for {name} {{")
        lines.append("    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {")
        lines.append("        match self {")
        for ident, _, _ in variants:
            lines.append(f"            Self::{ident}(inner) => inner.serialize(serializer),")
        lines.append("            Self::Unknown(inner) => inner.serialize(serializer),")
        lines.append("        }")
        lines.append("    }")
        lines.append("}")
        return lines

    def render_enum(self, name: str, values: list[str], description: str | None) -> list[str]:
        idents = [variant_ident(v) for v in values]
        if len(set(idents)) != len(idents) or "Other" in idents:
            raise GenerateError(f"enum {name} has colliding variants {values}")
        lines = docs(description)
        if lines:
            lines.append("///")
        lines += [
            "/// A value this release does not know is kept in `Other`, so a new value never fails a response.",
            "#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]",
            "#[non_exhaustive]",
            f"pub enum {name} {{",
        ]
        for ident, value in zip(idents, values):
            lines.append(f"    /// `{value}`")
            lines.append(f"    #[serde(rename = {rust_str(value)})]")
            lines.append(f"    {ident},")
        lines += [
            "    /// A value this release does not know, kept as sent.",
            "    #[serde(untagged)]",
            "    Other(String),",
            "}",
            "",
            f"impl {name} {{",
            "    /// The value as the API spells it.",
            "    pub fn as_str(&self) -> &str {",
            "        match self {",
        ]
        for ident, value in zip(idents, values):
            lines.append(f"            Self::{ident} => {rust_str(value)},")
        lines += [
            "            Self::Other(value) => value,",
            "        }",
            "    }",
            "}",
            "",
            f"impl From<&str> for {name} {{",
            "    fn from(value: &str) -> Self {",
            "        match value {",
        ]
        for ident, value in zip(idents, values):
            lines.append(f"            {rust_str(value)} => Self::{ident},")
        lines += [
            "            other => Self::Other(other.to_owned()),",
            "        }",
            "    }",
            "}",
            "",
            f"impl std::fmt::Display for {name} {{",
            "    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {",
            "        f.write_str(self.as_str())",
            "    }",
            "}",
            "",
            f"impl AsRef<str> for {name} {{",
            "    fn as_ref(&self) -> &str {",
            "        self.as_str()",
            "    }",
            "}",
        ]
        return lines

    def render_models(self) -> str:
        request = self.request_types()
        blocks: list[tuple[str, list[str]]] = []
        for name in self.structs:
            blocks.append((name, self.render_struct(name, name in request)))
        for name in self.unions:
            blocks.append((name, self.render_union(name)))
        for name, (values, description) in self.enum_defs.items():
            blocks.append((name, self.render_enum(name, values, description)))
        for name, (rust, description) in self.aliases.items():
            blocks.append((name, docs(description) + [f"pub type {name} = {rust};"]))
        names = [n for n, _ in blocks]
        if len(set(names)) != len(names):
            raise GenerateError(f"two types share a name: {sorted(n for n in names if names.count(n) > 1)}")
        blocks.sort(key=lambda block: block[0])
        uses = "use serde::{de, Deserialize, Deserializer, Serialize, Serializer};" if self.unions else "use serde::{Deserialize, Serialize};"
        out = [
            HEADER,
            "//! Typed models for every schema the OpenAPI document names, and for the request",
            "//! and response bodies it defines inline.",
            "//!",
            "//! A field the document marks optional or nullable is an `Option`: `None` means the",
            "//! API did not report that value, which is not a zero. Unknown JSON keys are ignored",
            "//! and an unknown enum value lands in `Other`, so an additive API change never fails",
            "//! a response. Money and price fields are `f64`, the precision the API sends.",
            "",
            "// Descriptions are the document's own, quoted verbatim; a field it leaves",
            "// undescribed has no doc comment rather than an invented one.",
            "#![allow(missing_docs)]",
            "#![allow(rustdoc::bare_urls, rustdoc::broken_intra_doc_links, rustdoc::invalid_html_tags)]",
            "#![allow(clippy::doc_lazy_continuation, clippy::large_enum_variant)]",
            "",
            uses,
            "",
        ]
        for _, lines in blocks:
            out.extend(lines)
            out.append("")
        return "\n".join(out).rstrip() + "\n"

    def render_operations(self, table: list[str], methods: list[str]) -> str:
        consts = re.findall(r"pub const ([A-Z0-9_]+): Operation", "\n".join(table))
        out = [
            HEADER,
            "//! The operation table, and one `Client` method per operation in the OpenAPI document.",
            "",
            "#![allow(rustdoc::bare_urls, rustdoc::broken_intra_doc_links, rustdoc::invalid_html_tags)]",
            "#![allow(clippy::doc_lazy_continuation, clippy::too_many_arguments)]",
            "",
            "use crate::client::{encode_path_segment, Call};",
            "use crate::models::*;",
            "use crate::pagination::{CursorParams, ListPage};",
            "use crate::{Client, Download, Operation, Result, RetryClass};",
            "",
            "impl Operation {",
        ]
        out.extend(table)
        out += [
            "}",
            "",
            "/// Every operation in the OpenAPI document, in document order.",
            "pub const OPERATIONS: &[Operation] = &[",
        ]
        out += [f"    Operation::{c}," for c in consts]
        out += ["];", ""]
        for lines in self.params.values():
            out.extend(lines)
            out.append("")
        out.append("impl Client {")
        out.extend(methods)
        while out[-1] == "":
            out.pop()
        out += ["}", ""]
        for response_type, (item, data_optional, has_more_optional, cursor_optional) in sorted(self.list_pages.items()):
            out += [
                f"impl ListPage for {response_type} {{",
                f"    type Item = {item};",
                "",
                f"    fn items(&self) -> &[{item}] {{",
                "        self.data.as_deref().unwrap_or_default()" if data_optional else "        &self.data",
                "    }",
                "",
                f"    fn into_items(self) -> Vec<{item}> {{",
                "        self.data.unwrap_or_default()" if data_optional else "        self.data",
                "    }",
                "",
                "    fn has_more(&self) -> bool {",
                "        self.has_more.unwrap_or(false)" if has_more_optional else "        self.has_more",
                "    }",
                "",
                "    fn next_cursor(&self) -> Option<&str> {",
                "        self.next_cursor.as_deref()" if cursor_optional else "        Some(&self.next_cursor)",
                "    }",
                "}",
                "",
            ]
        for params_type in sorted(self.cursor_params):
            out += [
                f"impl CursorParams for {params_type} {{",
                "    fn set_cursor(&mut self, cursor: Option<String>) {",
                "        self.cursor = cursor;",
                "    }",
                "}",
                "",
            ]
        return "\n".join(out).rstrip() + "\n"


